      PROGRAM X2CPROBE
C
C A PROBE, NOT A PRODUCTION PROGRAM: THE CCSD RESIDUAL OF CFOUR'S
C SPINOR CCSD (HBARSO OF XX2CCCSD ON THE ROUTINES OF LIBX2CCC) AGAINST
C THE CCSD PART OF THE NATIVE CCSDT STEP (CFOUR/XZCCSDT) ON THE SAME
C INTEGRAL FILES AND THE SAME AMPLITUDES, ELEMENT BY ELEMENT, AND THE
C WALL TIME OF BOTH.  RUNS WHERE XZCCSDT RUNS: AFTER XJODA, XSOX2CATM,
C XSOX2CHF AND XX2CVTRAN (ABCDTYPE=STANDARD), IN THEIR DIRECTORY.
C DOCS/NATIVE_X2CCC.MD.
C
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON//ICORE(1)
      COMMON/ISTART/I0
      COMMON/MACHSP/IINTLN,IFLTLN,IINTFP,IALONE,IBITWD
      COMMON/IOPOS/ICRSIZ,ICHSZ,IOFF(2),LENREC
C
      call initenv('MODULE')
      call walltime(0)
      CALL MCHPRM
      IENTRY=0
      CALL CRAPSI(ICORE,IUHF,IENTRY)
      MAXCOR=ICRSIZ/IINTFP
C
      CALL PROBEDRV(ICORE(I0),MAXCOR)
C
      CALL CRAPSO
      call walltime(1)
      STOP
      END
