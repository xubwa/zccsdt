      PROGRAM XZCCSDT
C
C SPINOR CCSDT AND CCSDT(Q) ENERGIES ON THE INTEGRAL FILES OF THE
C TWO-COMPONENT (X2CSO) PROGRAMS: RUNS AFTER XJODA, XSOX2CATM, XSOX2CHF
C AND XX2CVTRAN (ABCDTYPE=STANDARD) IN THEIR DIRECTORY.
C
C THE SCHEDULER IS IN FORTRAN (XZDRV AND BELOW), THE KERNELS ARE THE C
C KERNELS OF ZCCSDT (CSRC/).  ALL WORKING MEMORY IS THE ARRAY THAT CRAPSI
C ALLOCATES: ICORE(I0), MAXCOR DOUBLE WORDS (MEMORY_SIZE OF THE ZMAT).
C
C   xzccsdt [method]      method: ccsdt, ccsdt[q] or ccsdt(q); default:
C                         what CALC of the ZMAT asks for (JOBARC)
C
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON//ICORE(1)
      COMMON/ISTART/I0
      COMMON/MACHSP/IINTLN,IFLTLN,IINTFP,IALONE,IBITWD
      COMMON/IOPOS/ICRSIZ,ICHSZ,IOFF(2),LENREC
C
      call initenv('MODULE')
      call walltime(0)
C
C INITIALIZE PROGRAM IN THE CFOUR ENVIRONMENT
C
      CALL MCHPRM
      IENTRY=0
      CALL CRAPSI(ICORE,IUHF,IENTRY)
C
C SET MAXCOR IN FLOATING POINT WORDS
C
      MAXCOR=ICRSIZ/IINTFP
C
      CALL XZDRV(ICORE(I0),MAXCOR)
C
      CALL CRAPSO
      call walltime(1)
      STOP
      END
