      PROGRAM XZCCSDT
C
C SPINOR CCSDT AND CCSDT(Q) ENERGIES ON THE INTEGRAL FILES OF THE
C TWO-COMPONENT (X2CSO) PROGRAMS: RUNS AFTER XJODA, XSOX2CATM, XSOX2CHF
C AND XX2CVTRAN (ABCDTYPE=STANDARD) IN THEIR DIRECTORY.
C
C THE SCHEDULER IS IN FORTRAN (XZDRV AND BELOW), THE KERNELS ARE THE C
C KERNELS OF ZCCSDT (CSRC/).  ALL WORKING MEMORY IS THE ARRAY THAT CRAPSI
C ALLOCATES: ICORE(I0), MAXCOR DOUBLE WORDS (MEMORY_SIZE OF THE ZMAT).
C
C   xzccsdt               no argument: the job is what the ZMAT asks for
C                         (the flags of joda in JOBARC; XZJOB in xzdrv.F90):
C                         CALC=CCSDT, CCSDT[Q], CCSDT(Q), CCSDT(Q)_L, MP2;
C                         with CALC=CCSDT, EXCITE=EOMEE (EOM-EE-CCSDT) or
C                         PROPS / DERIV_LEV (the density files of xx2czvec).
C                         The amplitudes and lambda of an earlier run (files
C                         XZAMPS, XZLAMB, XZKEY) are taken when they belong
C                         to these integrals (XZREUSE)
C
C BUILT WITH MPI, THE ITERATIONS (CCSDT, LAMBDA) AND (Q) RUN OVER RANKS.
C RANK 0 IS THE CFOUR PROGRAM (CRAPSI, JOBARC, THE OUTPUT); THE OTHER
C RANKS GET JODA'S FLAGS FROM IT, ALLOCATE A WORK ARRAY OF THEIR OWN
C (GETMEM) - AS MANY WORDS AS THEIR PART TAKES WITH THE PLAN OF RANK 0 -
C AND WRITE TO xzccsdt.rNNNN.  IN THE ITERATIONS EVERY RANK HAS THE
C AMPLITUDES IN ITS WORK ARRAY (RANK 0 SENDS THEM); (Q) READS T3 WHERE
C THE FILE XZAMPS IS MAPPED.
C
      USE XZPAR
      USE XZDIST
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON//ICORE(1)
      COMMON/ISTART/I0
      COMMON/MACHSP/IINTLN,IFLTLN,IINTFP,IALONE,IBITWD
      COMMON/IOPOS/ICRSIZ,ICHSZ,IOFF(2),LENREC
      COMMON/FLAGS/IFLAGS(100)
      COMMON/FLAGS2/IFLAGS2(500)
      CHARACTER*13 FNOUT
      CHARACTER*32 CHV
      DIMENSION MXC(1)
C
      CALL XZMPI_INIT()
C THE WORDS OF ONE MPI MESSAGE: OPTION MPICHUNK OF %XZCCSDT (ZMAT)
      CALL X2C_GETOPT('xzccsdt','mpichunk',CHV,LCHV)
      IF(LCHV.GT.0)THEN
       READ(CHV(1:LCHV),*)NCHV
       CALL XZMPI_SET_CHUNK(NCHV)
      ENDIF
      MYRANK=XZMPI_RANK()
      NRANK=XZMPI_SIZE()
      IF(MYRANK.EQ.0)THEN
       call initenv('MODULE')
       call walltime(0)
C
C INITIALIZE PROGRAM IN THE CFOUR ENVIRONMENT
C
       CALL MCHPRM
       IENTRY=0
       CALL CRAPSI(ICORE,IUHF,IENTRY)
C
C SET MAXCOR IN FLOATING POINT WORDS
C
       MAXCOR=ICRSIZ/IINTFP
      ENDIF
      CALL XZMPI_BCAST(IFLAGS,800_8)
      CALL XZMPI_BCAST(IFLAGS2,4000_8)
      MXC(1)=MAXCOR
      CALL XZMPI_BCAST(MXC,8_8)
      MAXCOR=MXC(1)
      CALL XZMPISTART()
      IF(MYRANK.NE.0)THEN
       WRITE(FNOUT,'(A9,I4.4)')'xzccsdt.r',MYRANK
       OPEN(UNIT=6,FILE=FNOUT,FORM='FORMATTED',STATUS='REPLACE')
       CALL MCHPRM
C THE WORDS THAT THIS RANK TAKES WITH THE PLAN OF RANK 0 (WAITS FOR IT)
       CALL XZRANKMEM(MAXCOR)
       CALL GETMEM(MAXCOR*IINTFP,ICORE(1),I0)
       IF(I0.EQ.-1)THEN
        WRITE(6,*)'@XZCCSDT-F, no memory for the work array.'
        CALL XZMPI_ABORT(1_8)
       ENDIF
      ENDIF
C
      CALL XZDRV(ICORE(I0),MAXCOR)
C
      CALL XZMPI_FINALIZE()
      IF(MYRANK.EQ.0)THEN
       CALL CRAPSO
       call walltime(1)
      ENDIF
      STOP
      END
