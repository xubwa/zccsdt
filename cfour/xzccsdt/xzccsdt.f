      PROGRAM XZCCSDT
C
C SPINOR CCSDT AND CCSDT(Q) ENERGIES ON THE INTEGRAL FILES OF THE
C TWO-COMPONENT (X2CSO) PROGRAMS: RUNS AFTER XJODA, XSOX2CATM, XSOX2CHF
C AND XX2CVTRAN (ABCDTYPE=STANDARD) IN THEIR DIRECTORY.
C
C THE SCHEDULER IS IN FORTRAN (XZDRV AND BELOW), THE KERNELS ARE THE C
C KERNELS OF ZCCSDT (CSRC/).  ALL WORKING MEMORY IS THE ARRAY THAT CRAPSI
C ALLOCATES: ICORE(I0), MAXCOR DOUBLE WORDS (MEMORY_SIZE OF THE ZMAT).
C
C   xzccsdt [method]      method: ccsdt, ccsdt[q], ccsdt(q), or (q) / [q]
C                         for the correction alone from the amplitudes
C                         of an earlier run (file XZAMPS); lambda: the
C                         Lambda equations of CCSDT for these amplitudes
C                         (file XZLAMB); ccsdt(q)_l, ccsdt[q]_l, or
C                         (q)_l / [q]_l from XZAMPS and XZLAMB; default:
C                         what CALC of the ZMAT asks for (JOBARC)
C
C BUILT WITH MPI, (Q) IS PARALLEL OVER RANKS.  RANK 0 IS THE CFOUR
C PROGRAM (CRAPSI, JOBARC, THE OUTPUT); THE OTHER RANKS GET JODA'S FLAGS
C FROM IT, ALLOCATE THEIR OWN WORK ARRAY OF THE SAME SIZE (GETMEM) AND
C WRITE TO xzccsdt.rNNNN.
C
      USE XZPAR
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON//ICORE(1)
      COMMON/ISTART/I0
      COMMON/MACHSP/IINTLN,IFLTLN,IINTFP,IALONE,IBITWD
      COMMON/IOPOS/ICRSIZ,ICHSZ,IOFF(2),LENREC
      COMMON/FLAGS/IFLAGS(100)
      COMMON/FLAGS2/IFLAGS2(500)
      CHARACTER*13 FNOUT
      DIMENSION MXC(1)
C
      CALL XZMPI_INIT()
      MYRANK=XZMPI_RANK()
      NRANK=XZMPI_SIZE()
      IF(MYRANK.EQ.0)THEN
       call initenv('MODULE')
       call walltime(0)
C
C INITIALIZE PROGRAM IN THE CFOUR ENVIRONMENT
C
       CALL MCHPRM
       IENTRY=0
       CALL CRAPSI(ICORE,IUHF,IENTRY)
C
C SET MAXCOR IN FLOATING POINT WORDS
C
       MAXCOR=ICRSIZ/IINTFP
      ENDIF
      CALL XZMPI_BCAST(IFLAGS,800_8)
      CALL XZMPI_BCAST(IFLAGS2,4000_8)
      MXC(1)=MAXCOR
      CALL XZMPI_BCAST(MXC,8_8)
      MAXCOR=MXC(1)
      IF(MYRANK.NE.0)THEN
       WRITE(FNOUT,'(A9,I4.4)')'xzccsdt.r',MYRANK
       OPEN(UNIT=6,FILE=FNOUT,FORM='FORMATTED',STATUS='REPLACE')
       CALL MCHPRM
       CALL GETMEM(MAXCOR*IINTFP,ICORE(1),I0)
       IF(I0.EQ.-1)THEN
        WRITE(6,*)'@XZCCSDT-F, no memory for the work array.'
        CALL XZMPI_ABORT(1_8)
       ENDIF
      ENDIF
C
      CALL XZDRV(ICORE(I0),MAXCOR)
C
      CALL XZMPI_FINALIZE()
      IF(MYRANK.EQ.0)THEN
       CALL CRAPSO
       call walltime(1)
      ENDIF
      STOP
      END
